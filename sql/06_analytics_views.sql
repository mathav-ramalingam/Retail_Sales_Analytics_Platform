USE DATABASE RETAIL_SALES_DB;
USE SCHEMA ANALYTICS;


-- 1. Yearly Sales Analysis
CREATE OR REPLACE VIEW YEARLY_SALES_VW (
    ORDER_YEAR,
    TOTAL_RECORDS,
    TOTAL_SALES,
    AVG_SALES_PER_RECORD,
    TOTAL_NET_SALES,
    AVG_NET_SALES_PER_RECORD
) AS
SELECT
    ORDER_YEAR,
    COUNT(*) AS TOTAL_RECORDS,
    ROUND(SUM(SALES), 2) AS TOTAL_SALES,
    ROUND(AVG(SALES), 2) AS AVG_SALES_PER_RECORD,
    ROUND(SUM(NET_SALES), 2) AS TOTAL_NET_SALES,
    ROUND(AVG(NET_SALES), 2) AS AVG_NET_SALES_PER_RECORD
FROM RETAIL_SALES_DB.ANALYTICS.RETAIL_SALES_VW
GROUP BY ORDER_YEAR;

-- Verify the view
SELECT *
FROM YEARLY_SALES_VW
ORDER BY ORDER_YEAR;




-- =====================================================
-- 2. Category Sales Analysis
-- =====================================================

CREATE OR REPLACE VIEW CATEGORY_SALES_VW (
    CATEGORY,
    TOTAL_RECORDS,
    TOTAL_QUANTITY,
    TOTAL_SALES,
    TOTAL_NET_SALES
) AS
SELECT
    CATEGORY,
    COUNT(*) AS TOTAL_RECORDS,
    SUM(QUANTITY) AS TOTAL_QUANTITY,
    ROUND(SUM(SALES), 2) AS TOTAL_SALES,
    ROUND(SUM(NET_SALES), 2) AS TOTAL_NET_SALES
FROM RETAIL_SALES_DB.ANALYTICS.RETAIL_SALES_VW
GROUP BY CATEGORY;

-- Verify the view
SELECT *
FROM CATEGORY_SALES_VW
ORDER BY TOTAL_NET_SALES DESC;




-- =====================================================
-- 3. Regional Sales Analysis
-- =====================================================

CREATE OR REPLACE VIEW REGIONAL_SALES_VW (
    REGION,
    TOTAL_RECORDS,
    TOTAL_CUSTOMERS,
    TOTAL_SALES,
    TOTAL_NET_SALES
) AS
SELECT
    REGION,
    COUNT(*) AS TOTAL_RECORDS,
    COUNT(DISTINCT CUSTOMER_ID) AS TOTAL_CUSTOMERS,
    ROUND(SUM(SALES), 2) AS TOTAL_SALES,
    ROUND(SUM(NET_SALES), 2) AS TOTAL_NET_SALES
FROM RETAIL_SALES_DB.ANALYTICS.RETAIL_SALES_VW
GROUP BY REGION;

-- Verify the view
SELECT *
FROM REGIONAL_SALES_VW
ORDER BY TOTAL_NET_SALES DESC;



