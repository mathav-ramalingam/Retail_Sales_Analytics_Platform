-- =====================================================
-- 5. Shipping Performance Analysis
-- =====================================================

CREATE OR REPLACE VIEW SHIPPING_PERFORMANCE_VW (
    SHIP_MODE,
    TOTAL_RECORDS,
    AVG_DAYS_TO_SHIP,
    MIN_DAYS_TO_SHIP,
    MAX_DAYS_TO_SHIP
) AS
SELECT
    SHIP_MODE,
    COUNT(*) AS TOTAL_RECORDS,
    ROUND(AVG(DAYS_TO_SHIP), 2) AS AVG_DAYS_TO_SHIP,
    MIN(DAYS_TO_SHIP) AS MIN_DAYS_TO_SHIP,
    MAX(DAYS_TO_SHIP) AS MAX_DAYS_TO_SHIP
FROM RETAIL_SALES_DB.ANALYTICS.RETAIL_SALES_VW
GROUP BY SHIP_MODE;

-- Verify the view
SELECT *
FROM SHIPPING_PERFORMANCE_VW
ORDER BY AVG_DAYS_TO_SHIP;



-- =====================================================
-- 6. Top 10 Products Analysis
-- =====================================================

CREATE OR REPLACE VIEW TOP_PRODUCTS_VW (
    PRODUCT_ID,
    CATEGORY,
    SUB_CATEGORY,
    TOTAL_RECORDS,
    TOTAL_QUANTITY,
    TOTAL_SALES,
    TOTAL_NET_SALES
) AS
SELECT
    PRODUCT_ID,
    CATEGORY,
    SUB_CATEGORY,
    COUNT(*) AS TOTAL_RECORDS,
    SUM(QUANTITY) AS TOTAL_QUANTITY,
    ROUND(SUM(SALES), 2) AS TOTAL_SALES,
    ROUND(SUM(NET_SALES), 2) AS TOTAL_NET_SALES
FROM RETAIL_SALES_DB.ANALYTICS.RETAIL_SALES_VW
GROUP BY
    PRODUCT_ID,
    CATEGORY,
    SUB_CATEGORY
ORDER BY TOTAL_NET_SALES DESC
LIMIT 10;

-- Verify the view
SELECT *
FROM TOP_PRODUCTS_VW
ORDER BY TOTAL_NET_SALES DESC;

