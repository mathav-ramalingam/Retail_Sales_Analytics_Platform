-- Date validation
SELECT
    COUNT(*) AS TOTAL_RECORDS,
    COUNT_IF(ORDER_DATE IS NULL) AS NULL_ORDER_DATES,
    COUNT_IF(SHIP_DATE IS NULL) AS NULL_SHIP_DATES,
    COUNT_IF(SHIP_DATE < ORDER_DATE) AS SHIP_BEFORE_ORDER,
    COUNT_IF(DAYS_TO_SHIP < 0) AS NEGATIVE_SHIPPING_DAYS,
    COUNT_IF(
        DAYS_TO_SHIP != DATEDIFF(DAY, ORDER_DATE, SHIP_DATE)
    ) AS SHIPPING_DAY_MISMATCH,
    MIN(ORDER_DATE) AS EARLIEST_ORDER_DATE,
    MAX(ORDER_DATE) AS LATEST_ORDER_DATE
FROM RETAIL_SALES_DB.TRANSFORM.RETAIL_SALES_DEDUP;


-- Business rule validation
SELECT
    COUNT(*) AS TOTAL_RECORDS,
    COUNT_IF(PRICE <= 0) AS INVALID_PRICE,
    COUNT_IF(QUANTITY <= 0) AS INVALID_QUANTITY,
    COUNT_IF(DISCOUNT < 0 OR DISCOUNT > 1) AS INVALID_DISCOUNT,
    COUNT_IF(SALES != PRICE * QUANTITY) AS GROSS_SALES_MISMATCH,
    COUNT_IF(
        ABS(NET_SALES - PRICE * QUANTITY * (1 - DISCOUNT)) > 0.00001
    ) AS NET_SALES_MISMATCH,
    COUNT_IF(ORDER_YEAR != YEAR(ORDER_DATE)) AS INVALID_ORDER_YEAR
FROM RETAIL_SALES_DB.TRANSFORM.RETAIL_SALES_DEDUP;



-- Final financial reconciliation
SELECT
    ROUND(SUM(SALES), 2) AS TOTAL_GROSS_SALES,
    ROUND(
        SUM(SALES * DISCOUNT), 2
    ) AS TOTAL_DISCOUNT,
    ROUND(SUM(NET_SALES), 2) AS TOTAL_NET_SALES,
    ROUND(
        SUM(SALES) - SUM(SALES * DISCOUNT) - SUM(NET_SALES),
        2
    ) AS RECONCILIATION_DIFFERENCE
FROM RETAIL_SALES_DB.TRANSFORM.RETAIL_SALES_DEDUP;



