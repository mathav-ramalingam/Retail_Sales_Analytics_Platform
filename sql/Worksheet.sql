FROM RETAIL_SALES_DB.TRANSFORM.RETAIL_SALES_CLEAN;

SELECT
    ORDER_ID,
    PRODUCT_ID,
    COUNT(*) AS DUPLICATE_COUNT
FROM RETAIL_SALES_DB.TRANSFORM.RETAIL_SALES_CLEAN
GROUP BY ORDER_ID, PRODUCT_ID
HAVING COUNT(*) > 1
ORDER BY DUPLICATE_COUNT DESC;


SELECT
    ORDER_ID,
    PRODUCT_ID,
    PRICE,
    QUANTITY,
    DISCOUNT,
    COUNT(*) AS RAW_COUNT
FROM RETAIL_SALES_DB.RAW.RETAIL_ORDERS_RAW
